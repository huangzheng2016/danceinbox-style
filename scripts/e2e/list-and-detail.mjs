import { chromium } from 'playwright'
const base = process.env.E2E_BASE ?? 'http://127.0.0.1:8080'
const shots = process.env.E2E_SHOTS ?? 'shots'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
let failed = 0
const step = async (name, fn) => {
  try { await fn(); console.log('ok  ', name) }
  catch (e) { failed++; console.log('FAIL', name, e.message.split('\n')[0]); await page.screenshot({ path: `${shots}/fail-${name.slice(0, 20)}.png` }) }
}
const api = (path, body) => page.evaluate(([p, b]) => fetch(p, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(b) }).then((r) => r.json()), [path, body])

await page.goto(base + '/#/login')
await page.fill('input[autocomplete=username]', 'admin')
await page.fill('input[type=password]', 'password1')
await page.click('button[type=submit]')
await page.waitForURL(/#\/$/)
for (const [name, enabled] of [['订单同步', true], ['库存校准', false], ['报表导出', true], ['日志归档', false]])
  await api('/api/example/create', { name, remark: '', enabled, owner_id: '0' })

await step('owner picker searches the server and saves', async () => {
  await page.goto(base + '/#/examples')
  await page.click('button.primary:has-text("新建")')
  await page.fill('.dialog input[maxlength="64"]', '用户画像刷新')
  await page.click('.dialog .combo')
  await page.keyboard.type('al')
  await page.waitForFunction(() => document.querySelectorAll('[role=option]').length === 2)
  const names = await page.locator('[role=option]').allTextContents()
  if (names.map((n) => n.trim()).join() !== 'albert,alice') throw new Error('got ' + names)
  await page.screenshot({ path: `${shots}/20-combobox.png` })
  await page.click('[role=option]:has-text("alice")')
  await page.click('.dialog-foot button.primary')
  await page.locator('.toast', { hasText: '已创建' }).waitFor()
  await page.locator('tbody tr', { hasText: '用户画像刷新' }).locator('td', { hasText: 'alice' }).waitFor()
})
await step('sort by name puts it in the URL and reorders', async () => {
  await page.click('th[aria-sort] button:has-text("名称")')
  await page.waitForURL(/sort=name/)
  await page.waitForFunction(() => document.querySelector('tbody tr td:nth-child(2)')?.textContent?.trim() === '库存校准')
})
await step('status segmented filters', async () => {
  await page.click('[role=radio]:has-text("已停用")')
  await page.waitForURL(/status=disabled/)
  await page.waitForFunction(() => document.querySelectorAll('tbody tr.clickable').length === 2)
  await page.click('[role=radio]:has-text("全部")')
  await page.waitForFunction(() => document.querySelectorAll('tbody tr.clickable').length === 5)
})
await step('date range: today includes all, custom past range shows filtered empty state', async () => {
  await page.selectOption('.date-range select', 'today')
  await page.waitForURL(/range=today/)
  await page.waitForFunction(() => document.querySelectorAll('tbody tr.clickable').length === 5)
  await page.selectOption('.date-range select', 'custom')
  await page.fill('input[aria-label=开始日期]', '2020-01-01')
  await page.fill('input[aria-label=结束日期]', '2020-01-02')
  await page.locator('input[aria-label=结束日期]').dispatchEvent('change')
  await page.getByText('没有符合条件的示例').waitFor()
  await page.click('button:has-text("清除筛选")')
  await page.waitForFunction(() => document.querySelectorAll('tbody tr.clickable').length === 5)
})
await step('batch disable then batch delete reports skipped rows', async () => {
  const rows = page.locator('tbody tr.clickable')
  await rows.nth(0).locator('td.col-check input').check()
  await rows.nth(1).locator('td.col-check input').check()
  await rows.nth(2).locator('td.col-check input').check()
  await page.locator('.toolbar.batch', { hasText: '已选 3 项' }).waitFor()
  await page.screenshot({ path: `${shots}/21-batch.png` })
  await page.click('.toolbar.batch button:has-text("停用")')
  await page.locator('.toast', { hasText: '已停用 3 项' }).waitFor()
  await page.click('thead input[type=checkbox]')
  await page.click('.toolbar.batch button:has-text("删除")')
  await page.click('.dialog-foot button.danger')
  await page.locator('.toast', { hasText: /已删除 3 项，跳过 2 项/ }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('tbody tr.clickable').length === 2)
})
await step('detail page: breadcrumb, disabled banner enables, raw JSON tab', async () => {
  const list = await page.evaluate(() => fetch('/api/example/list').then((r) => r.json()))
  const target = list.items[0]
  await api('/api/example/set_enabled', { id: target.id, enabled: false })
  await page.click(`tbody tr.clickable:has-text("${target.name}")`)
  await page.click('a:has-text("完整详情")')
  await page.waitForURL(new RegExp(`#/examples/${target.id}`))
  await page.locator('header .crumb', { hasText: '示例' }).waitFor()
  await page.locator('header h1', { hasText: target.name }).waitFor()
  await page.screenshot({ path: `${shots}/22-detail.png` })
  await page.locator('.alert', { hasText: '已停用' }).locator('button:has-text("启用")').click()
  await page.locator('.toast', { hasText: '已启用' }).waitFor()
  await page.locator('.alert').waitFor({ state: 'detached' })
  await page.click('[role=tab]:has-text("原始数据")')
  await page.waitForURL(/tab=raw/)
  await page.locator('.code-block .tok-key', { hasText: '"owner_id"' }).first().waitFor()
  await page.screenshot({ path: `${shots}/23-raw.png` })
})
await step('unsaved edits ask before the dialog closes', async () => {
  await page.click('[role=tab]:has-text("概览")')
  await page.click('.toolbar button:has-text("编辑")')
  await page.fill('.dialog input[maxlength="64"]', '改过的名字')
  await page.keyboard.press('Escape')
  const top = page.locator('.dialog', { has: page.locator('h2', { hasText: '放弃修改' }) })
  await top.waitFor()
  await page.waitForTimeout(300)
  await page.screenshot({ path: `${shots}/24-dirty.png` })
  await top.locator('button', { hasText: '取消' }).click()
  await top.waitFor({ state: 'detached' }).catch(() => {})
  if ((await page.locator('.dialog input[maxlength="64"]').inputValue()) !== '改过的名字') throw new Error('edits lost')
  await page.locator('.dialog .dialog-foot button', { hasText: '取消' }).click()
  await top.locator('button.danger', { hasText: '放弃修改' }).click()
  await page.waitForFunction(() => document.querySelectorAll('.dialog').length === 0)
})
await step('breadcrumb returns to the list', async () => {
  await page.click('header .crumb')
  await page.waitForURL(/#\/examples$/)
})
await step('home shows real counts with progress', async () => {
  await page.goto(base + '/#/')
  await page.locator('[role=progressbar]').waitFor()
  await page.screenshot({ path: `${shots}/25-home.png` })
})
const dark = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' })
await dark.addCookies(await ctx.cookies())
const dp = await dark.newPage()
await dp.goto(base + '/#/examples?sort=-name')
await dp.waitForTimeout(700)
await dp.click('button.primary:has-text("新建")')
await dp.click('.dialog .combo')
await dp.waitForTimeout(500)
await dp.screenshot({ path: `${shots}/26-dark-form.png` })
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 } })
await mobile.addCookies(await ctx.cookies())
const mp = await mobile.newPage()
await mp.goto(base + '/#/examples')
await mp.waitForTimeout(700)
await mp.screenshot({ path: `${shots}/27-mobile-toolbar.png` })
console.log('page errors:', errors.length ? errors : 'none', '| failed:', failed)
await browser.close()
if (errors.length || failed) process.exit(1)
